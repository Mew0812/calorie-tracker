import { expect,test,type Page } from '@playwright/test'
const nav=(page:Page,name:string)=>page.getByRole('navigation').getByRole('button',{name,exact:true})
async function registerFood(page:Page) {
  await nav(page,'食品').click()
  await page.getByRole('button',{name:'食品を新規作成',exact:true}).click()
  await page.getByRole('textbox',{name:'食品名',exact:true}).fill('検証の卵')
  await page.getByRole('textbox',{name:'単位',exact:true}).fill('1個')
  for(const [label,value] of [['カロリー（kcal）','75'],['タンパク質（g）','6'],['脂質（g）','5'],['炭水化物（g）','1']])await page.getByRole('spinbutton',{name:label,exact:true}).fill(value)
  await page.getByRole('button',{name:'保存する',exact:true}).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
}
async function readStore(page:Page,name:string) {
  return page.evaluate(name=>new Promise<unknown[]>((resolve,reject)=>{
    const opening=indexedDB.open('MyDiet')
    opening.onsuccess=()=>{const db=opening.result,tx=db.transaction(name,'readonly'),get=tx.objectStore(name).getAll();get.onsuccess=()=>resolve(get.result);tx.oncomplete=()=>db.close();tx.onerror=()=>reject(tx.error)}
  }),name)
}
test.beforeEach(async({page})=>{
  await page.clock.setFixedTime(new Date('2026-11-23T12:00:00+09:00'))
  await page.goto('/')
})
test('compact archived-food sets, single-flight addition, header undo and four even tabs',async({page},testInfo)=>{
  await registerFood(page)
  await page.getByRole('main').getByRole('button',{name:'セット',exact:true}).click()
  await page.getByRole('button',{name:'食品セットを新規作成',exact:true}).click()
  await page.getByRole('textbox',{name:'セット名',exact:true}).fill('朝食セット')
  await page.getByRole('combobox',{name:'追加する食品',exact:true}).selectOption({label:'検証の卵'})
  await page.getByRole('button',{name:'追加',exact:true}).click()
  await page.getByRole('spinbutton',{name:'数量',exact:true}).fill('2')
  await page.getByRole('button',{name:'保存する',exact:true}).click()
  await page.getByRole('main').getByRole('button',{name:'食品',exact:true}).click()
  await page.getByRole('button',{name:'保管',exact:true}).click()
  await nav(page,'記録').click()
  const card=page.getByRole('button',{name:'朝食セット',exact:true}),undo=page.getByRole('button',{name:'直前の追加を取り消す',exact:true})
  await expect(card).toBeEnabled()
  await expect(card.locator('small')).toHaveCount(0)
  await expect(card.locator('svg')).toHaveCount(1)
  await expect(undo).toHaveCount(0)
  await card.evaluate((element:HTMLButtonElement)=>{element.click();element.click()})
  await expect.poll(async()=>((await readStore(page,'entries'))[0] as {count:number})?.count).toBe(2)
  await expect(undo).toBeEnabled()
  await card.click()
  await expect.poll(async()=>((await readStore(page,'entries'))[0] as {count:number})?.count).toBe(4)
  for(const width of [320,375,390]) {
    await page.setViewportSize({width,height:844})
    const heading=page.getByRole('heading',{name:'食品セット',exact:true}),a=await heading.boundingBox(),b=await undo.boundingBox()
    expect(a&&b&&a.x+a.width<=b.x).toBeTruthy()
    expect(b!.height).toBeGreaterThanOrEqual(44)
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=document.documentElement.clientWidth)).toBe(true)
    const tabs=await page.getByRole('navigation').getByRole('button').all()
    expect(await page.getByRole('navigation').getByRole('button').allTextContents()).toEqual(['記録','分析','食品','設定'])
    const widths=await Promise.all(tabs.map(async tab=>(await tab.boundingBox())!.width))
    expect(Math.max(...widths)-Math.min(...widths)).toBeLessThan(1)
  }
  await page.screenshot({path:testInfo.outputPath('set-heading.png'),fullPage:true})
  await undo.click()
  await expect(undo).toHaveCount(0)
  await expect.poll(async()=>((await readStore(page,'entries'))[0] as {count:number})?.count).toBe(2)
  await page.reload()
  await expect.poll(async()=>((await readStore(page,'entries'))[0] as {count:number})?.count).toBe(2)
  await expect(card).toBeEnabled()
  expect((await readStore(page,'foods'))[0]).toMatchObject({archived:true})
})

test('history lives in settings, preserves past edits and handles back, forward and reload safely',async({page})=>{
  await registerFood(page)
  await nav(page,'記録').click()
  await page.getByRole('button',{name:'検証の卵を1増やす',exact:true}).click()
  await nav(page,'設定').click()
  const settings=page.getByRole('heading',{name:'アプリ設定',exact:true}).locator('..')
  const panel=page.locator('section.card.detail').filter({has:settings})
  expect(await panel.locator(':scope > :last-child').innerText()).toContain('外観')
  expect(await panel.getByRole('button').allTextContents()).toEqual(['アプリアイコン ','筋トレ日・休養日の目標 ','バックアップ・復元 ','履歴 '])
  await page.getByRole('button',{name:'履歴',exact:true}).click()
  await expect(page.getByRole('heading',{name:'履歴',exact:true})).toBeVisible()
  await expect(nav(page,'設定')).toHaveAttribute('aria-current','page')
  await expect(nav(page,'カレンダー')).toHaveCount(0)
  await page.getByRole('button',{name:'11月22日(日) 未記録',exact:true}).click()
  await page.getByRole('button',{name:'この日の記録を編集',exact:true}).click()
  await page.getByRole('button',{name:'検証の卵を1増やす',exact:true}).click()
  await page.getByRole('button',{name:'検証の卵を1増やす',exact:true}).click()
  await page.getByRole('button',{name:'詳細に戻る',exact:true}).click()
  await expect(page.getByRole('button',{name:'11月22日(日) 記録完了',exact:true})).toBeVisible()
  await expect(page.getByRole('button',{name:'11月24日(火) 未記録',exact:true})).toBeDisabled()
  const entries=await readStore(page,'entries')
  expect(entries).toEqual(expect.arrayContaining([expect.objectContaining({date:'2026-11-22',count:2}),expect.objectContaining({date:'2026-11-23',count:1})]))
  await page.getByRole('button',{name:'設定に戻る',exact:true}).click()
  await expect(page.getByRole('heading',{name:'設定',exact:true})).toBeVisible()
  await page.getByRole('button',{name:'履歴',exact:true}).click()
  await page.goBack()
  await expect(page.getByRole('heading',{name:'設定',exact:true})).toBeVisible()
  await page.goForward()
  await expect(page.getByRole('heading',{name:'履歴',exact:true})).toBeVisible()
  await page.reload()
  await nav(page,'設定').click()
  await page.getByRole('button',{name:'履歴',exact:true}).click()
  await page.getByRole('button',{name:'設定に戻る',exact:true}).click()
  await expect(page.getByRole('heading',{name:'設定',exact:true})).toBeVisible()
  await page.getByRole('button',{name:'履歴',exact:true}).click()
  await nav(page,'記録').click()
  await expect(page.getByRole('status',{name:'検証の卵の数量',exact:true})).toHaveText('1')
  expect(await readStore(page,'entries')).toEqual(entries)
})
